const fabricateWhenCondition = (condition, mappings) => [
  condition,
  {
    is: Joi.valid(...Object.keys(mappings)),
    then: Joi.string().custom((targetValue, helpers) => {
      const { [condition]: conditionValue } = helpers.state.ancestors[0];
      const { path: target } = helpers.state;
      const validTargetValues = mappings[conditionValue];
      if (validTargetValues.includes(targetValue)) {
        return targetValue;
      }
      return helpers.error('any.custom', {
        target,
        targetValue,
        validTargetValues,
        condition,
        conditionValue,
      });
    }),
  },
];

export const adCreativeMappingsSchema = Joi.object({
  optimization_goal: Joi.string().required(),
  objective: Joi.string().required(),
  adgroup_type: Joi.string(),
  ad_type: Joi.string()
    .required()
    .when(...fabricateWhenCondition('adgroup_type', adGroupTypeToAdTypeMapping))
    .when(...fabricateWhenCondition('optimization_goal', optimizationGoalToAdTypesMapping)),
  creative_type: Joi.string()
    .required()
    .when(...fabricateWhenCondition('ad_type', adTypeToCreativeTypeMapping))
    .when(...fabricateWhenCondition('optimization_goal', optimizationGoalToCreativeTypesMapping))
    .when(...fabricateWhenCondition('adgroup_type', adGroupToCreativeTypeMapping)),
  call_to_action: Joi.string()
    .required()
    .when(...fabricateWhenCondition('creative_type', creativeTypeToCallToActionMapping)),
}).error((errors) => {
  errors.forEach((err) => {
    const {
      code,
      local: { target, validTargetValues, condition, conditionValue },
    } = err;
    if (code === 'any.custom') {
      err.message = `When '${condition} = ${conditionValue}', ${target} must be one of [${validTargetValues.join(', ')}]`;
    }
  });
  return errors;
});
